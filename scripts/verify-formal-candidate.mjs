import {readFileSync,writeFileSync,mkdtempSync,copyFileSync,unlinkSync,rmdirSync,mkdirSync,existsSync,readdirSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {join,resolve,basename} from 'node:path';
import {tmpdir} from 'node:os';
import {fileURLToPath} from 'node:url';
import {verifyUpdaterSignature,certificateDetails,validateApkEvidence} from './formal-release-support.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const [androidArg,windowsArg,outArg]=process.argv.slice(2);
if(!androidArg||!windowsArg||!outArg) throw new Error('Supply Android APK, Windows installer, and a new metadata directory.');
const android=resolve(androidArg),windows=resolve(windowsArg),out=resolve(outArg);
const productionRoot=resolve(root,'production-artifacts')+'\\';
if(![android,windows,out].every(path=>path.toLowerCase().startsWith(productionRoot.toLowerCase()))) throw new Error('Formal artifacts must stay in production-artifacts.');
if(existsSync(out)&&readdirSync(out).length) throw new Error('Existing candidate metadata is immutable; choose a fresh directory.');
const version=JSON.parse(readFileSync(join(root,'web/package.json'),'utf8')).version;
const gradle=readFileSync(join(root,'web/android/app/build.gradle'),'utf8');
const code=Number(gradle.match(/versionCode[^\n]*'([0-9]+)'/)?.[1]);
if(!basename(windows).includes(`_${version}_`)||!basename(android).endsWith('-release.apk')) throw new Error('Installer filename/version mismatch.');
const keyRoot=join(root,'.release-signing');
const certificate=certificateDetails(readFileSync(join(keyRoot,'android-release.der')));
const pub=readFileSync(join(keyRoot,'windows-updater.key.pub'),'utf8');
const signingEvidence=verifyUpdaterSignature(readFileSync(windows),pub,readFileSync(windows+'.sig','utf8'));
const sdk=process.env.ANDROID_HOME||join(root,'.desktop-tools/android-sdk');
const jdk=process.env.JAVA_HOME||'E:/biancheng/JDK21';
const tools=join(sdk,'build-tools/36.0.0');
const temp=mkdtempSync(join(tmpdir(),'plan-formal-apk-'));
let apkEvidence;
try {
  copyFileSync(android,join(temp,'client.apk'));
  const badging=execFileSync(join(tools,'aapt.exe'),['dump','badging','client.apk'],{cwd:temp,encoding:'utf8'});
  const signatures=execFileSync(join(jdk,'bin/java.exe'),['-jar',join(tools,'lib/apksigner.jar'),'verify','--verbose','--print-certs','client.apk'],{cwd:temp,encoding:'utf8'});
  apkEvidence=validateApkEvidence(badging,signatures,version,code,certificate.certificateSHA256);
  execFileSync(join(jdk,'bin/jar.exe'),['xf','client.apk','assets/capacitor.config.json'],{cwd:temp});
  const capacitor=JSON.parse(readFileSync(join(temp,'assets/capacitor.config.json'),'utf8'));
  if(capacitor.appId!==apkEvidence.packageName) throw new Error('Bundled Capacitor identity does not match the signed APK.');
  const manifest=execFileSync(join(tools,'aapt.exe'),['dump','xmltree','client.apk','AndroidManifest.xml'],{cwd:temp,encoding:'utf8'});
  if(/android:usesCleartextTraffic[^\n]*0xffffffff/.test(manifest)||/android:debuggable[^\n]*0xffffffff/.test(manifest)) throw new Error('Formal manifest enables cleartext or debugging.');
} finally {
  for(const path of ['assets/capacitor.config.json','client.apk']) if(existsSync(join(temp,path))) unlinkSync(join(temp,path));
  if(existsSync(join(temp,'assets'))) rmdirSync(join(temp,'assets'));
  rmdirSync(temp);
}
const hash=path=>createHash('sha256').update(readFileSync(path)).digest('hex');
const artifact=path=>({file:basename(path),bytes:readFileSync(path).length,sha256:hash(path)});
const record={schemaVersion:1,version,status:'LOCAL_SIGNED_CANDIDATE',readyForPublicDownload:false,publicRegistrationEnabled:false,requires:['Portable signing backup','Formal installers installation acceptance','APP ICP filing and public release approval'],windows:{...artifact(windows),updaterSignatureVerified:true,...signingEvidence,authenticode:'Not provided; publisher identity is not certified'},android:{...artifact(android),...apkEvidence,debuggable:false,cleartextTraffic:false}};
const filing={appName:'计划舱',packageName:apkEvidence.packageName,version,versionCode:code,backendDomain:'plan.zijun701.cn',appIcpFilingNumber:null,...certificate};
mkdirSync(join(out,'filing'),{recursive:true});
writeFileSync(join(out,'candidate.json'),JSON.stringify(record,null,2)+'\n');
writeFileSync(join(out,'filing/android-app-features.json'),JSON.stringify(filing,null,2)+'\n');
writeFileSync(join(out,'filing/android-public-key.pem'),certificate.publicKeyPem);
copyFileSync(join(keyRoot,'android-release.der'),join(out,'filing/android-certificate.der'));
copyFileSync(join(keyRoot,'windows-updater.key.pub'),join(out,'windows-updater.pub'));
writeFileSync(join(out,'downloads-manifest.json'),JSON.stringify({schemaVersion:1,windows:null,android:null},null,2)+'\n');
writeFileSync(join(out,'downloads-manifest.pending.json'),JSON.stringify({schemaVersion:1,windows:{version,url:'/downloads/'+version+'/'+encodeURIComponent(basename(windows)),...artifact(windows)},android:{version,url:'/downloads/'+version+'/'+basename(android),...artifact(android)}},null,2)+'\n');
console.log(`Verified formal ${version}: new release APK + real Windows updater signature. No public upload, installation or registration change.`);
console.log(`Candidate evidence and public APP filing features: ${out}`);
